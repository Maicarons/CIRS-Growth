#!python
"""Generate settings_text.nut from the Game Script language files.

OpenTTD captures GS settings descriptions and AddLabels values as RAW strings
at *scan* time (src/script/script_info.cpp -> StrMakeValid), before any
translation is loaded.  A running game cannot translate them.  So we keep one
source of truth in lang/*.txt (STR_SETTINGS_* keys) and generate a plain
Squirrel table at *build* time.  info.nut loads it with
require("settings_text.nut") and passes the values to AddSetting/AddLabels.

make_tar.py --lang <name> calls generate(<name>, <tmp_dir>/settings_text.nut)
before packing, so every packaged .tar ships a settings menu in the requested
language.  All language files still ship in lang/ for runtime GSText strings
(StoryBook, town signs, ...), which OpenTTD localizes normally.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANG_DIR = os.path.join(ROOT, "lang")
OUT_FILE = os.path.join(ROOT, "settings_text.nut")

# AddSetting names, in the exact order they appear in info.nut.
SETTING_NAMES = [
    "town_info_mode", "goal_scale_factor", "use_town_sign", "eternal_love",
    "cargo_6_category", "cargo_randomization", "near_cargo_probability",
    "display_cargo", "raw_industry_density", "limit_min_transport",
    "town_size_threshold", "limiter_delay", "subsidies_type",
    "category_1_min_pop", "category_2_min_pop", "category_3_min_pop",
    "category_4_min_pop", "category_5_min_pop", "category_6_min_pop",
    "town_growth_factor", "supply_impacting_part", "exponentiality_factor",
    "lowest_town_growth_rate", "allow_0_days_growth", "log_level",
]

# (AddLabels name, first label index, last label index) -- matches info.nut.
LABEL_GROUPS = [
    ("town_info_mode", 1, 5),
    ("eternal_love", 0, 3),
    ("cargo_randomization", 1, 15),
    ("raw_industry_density", 0, 5),
    ("subsidies_type", 0, 3),
    ("log_level", 1, 3),
]

LINE_RE = re.compile(r"^\s*(STR_[A-Za-z0-9_]+)\s*:(.*)$")


def desc_key(name):
    return "STR_SETTINGS_DESC_" + name.upper()


def label_key(name, n):
    return "STR_SETTINGS_LABEL_%s_%d" % (name.upper(), n)


def read_lang(name):
    """Return {key: text} for lang/<name>.txt (UTF-8, any newline style)."""
    path = os.path.join(LANG_DIR, name + ".txt")
    if not os.path.isfile(path):
        raise SystemExit("[GEN SETTINGS] language file not found: " + path)
    result = {}
    with open(path, "r", encoding="utf-8-sig", newline=None) as fp:
        for raw in fp:
            line = raw.rstrip("\r\n")
            if not line or line.lstrip().startswith("#"):
                continue
            m = LINE_RE.match(line)
            if m is None:
                raise SystemExit("[GEN SETTINGS] malformed line in %s: %s" % (path, line))
            key, text = m.group(1), m.group(2)
            if key in result:
                raise SystemExit("[GEN SETTINGS] duplicate key %s in %s" % (key, path))
            result[key] = text.lstrip()
    return result


def check_lang(strings, name):
    """Missing keys would silently fall back to English; catch them instead."""
    keys = [desc_key(n) for n in SETTING_NAMES]
    for nm, lo, hi in LABEL_GROUPS:
        keys += [label_key(nm, n) for n in range(lo, hi + 1)]
    missing = [k for k in keys if k not in strings]
    if missing:
        raise SystemExit("[GEN SETTINGS] %s.txt is missing %d keys: %s" %
                         (name, len(missing), ", ".join(missing[:8])))
    for k in keys:
        text = strings[k]
        # Descriptions/labels are drawn via {RAW_STRING}: literal braces would
        # be parsed as format codes, and double quotes would break the .nut.
        if "{" in text or "}" in text:
            raise SystemExit("[GEN SETTINGS] %s.txt: %s contains { } (format code)" % (name, k))
        if '"' in text:
            raise SystemExit("[GEN SETTINGS] %s.txt: %s contains a double quote" % (name, k))
    return keys


def squirrel_escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def generate(lang="english", out_file=None):
    """Write the settings_text.nut table for <lang>; returns the output path."""
    if out_file is None:
        out_file = OUT_FILE
    strings = read_lang(lang)
    check_lang(strings, lang)
    lines = [
        "// Generated by tools/gen_settings.py -- do not edit by hand.",
        "// Source: lang/%s.txt   (build-time i18n for the GS settings menu)" % lang,
        '// Loaded by info.nut via require("settings_text.nut").',
        "//",
        "// OpenTTD captures these strings at scan time, before translations",
        "// load, so the menu language is fixed when the .tar is built.",
        "",
        "::SettingsDesc <- {",
    ]
    for name in SETTING_NAMES:
        lines.append('    %s = "%s",' % (name, squirrel_escape(strings[desc_key(name)])))
    lines.append("};")
    lines.append("")
    lines.append("::SettingsLabel <- {")
    for name, lo, hi in LABEL_GROUPS:
        lines.append("    %s = {" % name)
        for n in range(lo, hi + 1):
            lines.append('        _%d = "%s",' % (n, squirrel_escape(strings[label_key(name, n)])))
        lines.append("    },")
    lines.append("};")
    lines.append("")
    with open(out_file, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("\n".join(lines))
    return out_file


if __name__ == "__main__":
    import argparse
    p = argparse.ArgumentParser(description="Generate settings_text.nut for one GS language")
    p.add_argument("--lang", default="english", help="language file basename in lang/ (default: english)")
    p.add_argument("--out", default=None, help="output .nut path (default: repo-root settings_text.nut)")
    a = p.parse_args()
    out = generate(a.lang, a.out)
    print("[GEN SETTINGS] wrote %s from lang/%s.txt" % (out, a.lang))
